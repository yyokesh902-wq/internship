export const getTemplateById = (id?: string): TemplateDefinition => {
  if (!id) return TEMPLATES_DATA[0];

  // Match exact ID
  const directMatch = TEMPLATES_DATA.find((t) => t.id === id);
  if (directMatch) return directMatch;

  // Backward compatibility aliases
  if (id === 'classic') return TEMPLATES_DATA[0]; // Classic Black
  if (id === 'modern') return TEMPLATES_DATA[10]; // Modern Blue
  if (id === 'minimal') return TEMPLATES_DATA[20]; // Minimal
  if (id === 'creative') return TEMPLATES_DATA[62]; // Creative

  // Match by slug / clean lowercase
  const normalized = id.toLowerCase().replace(/[^a-z0-9]/g, '-');
  const slugMatch = TEMPLATES_DATA.find((t) => t.id === normalized || t.name.toLowerCase().replace(/[^a-z0-9]/g, '-') === normalized);
  if (slugMatch) return slugMatch;

  return TEMPLATES_DATA[0];
};
